#!/usr/bin/env bash
# infra/neon/setup.sh
#
# Runs setup.sql against the Neon database and writes one env file per app
# (<app>.env, mode 600) into SECRETS_DIR. Prints names and status only, never
# a connection string, password or secret.
#
# Usage:
#   SECRETS_DIR=/path/to/secrets ./setup.sh            # keep existing passwords
#   SECRETS_DIR=/path/to/secrets ./setup.sh --rotate   # new DB passwords + JWT secrets
#
# Input:  $SECRETS_DIR/neon.env (or $NEON_ENV) with the admin URLs
#           DATABASE_URL         direct host
#           DATABASE_URL_POOLED  -pooler host
# Output: $SECRETS_DIR/{trustit,amscars,sift,nexus}.env
#
# Requires: psql, openssl, python3.

set -euo pipefail
umask 077

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SECRETS_DIR="${SECRETS_DIR:?set SECRETS_DIR to the folder holding neon.env}"
NEON_ENV="${NEON_ENV:-$SECRETS_DIR/neon.env}"
ROTATE=0
[[ "${1:-}" == "--rotate" ]] && ROTATE=1

APPS=(trustit amscars sift nexus)

[[ -r "$NEON_ENV" ]] || { echo "error: cannot read admin env file" >&2; exit 1; }

# Load admin URLs into this shell only. Never echoed.
set -a
# shellcheck disable=SC1090
. "$NEON_ENV"
set +a
: "${DATABASE_URL:?admin env file has no DATABASE_URL}"
: "${DATABASE_URL_POOLED:?admin env file has no DATABASE_URL_POOLED}"
ADMIN_URL="$DATABASE_URL"
ADMIN_URL_POOLED="$DATABASE_URL_POOLED"
unset DATABASE_URL DATABASE_URL_POOLED

# Pull a value out of an existing app env file (empty if absent).
#   existing <app> pw   -> password inside DATABASE_URL
#   existing <app> jwt  -> JWT_SECRET
existing() {
  local file="$SECRETS_DIR/$1.env"
  [[ -r "$file" ]] || { printf ''; return; }
  python3 -I - "$file" "$2" <<'PY'
import sys, urllib.parse as u
path, what = sys.argv[1], sys.argv[2]
vals = {}
for line in open(path, encoding="utf-8"):
    line = line.strip()
    if line and not line.startswith("#") and "=" in line:
        k, v = line.split("=", 1)
        vals[k] = v.strip().strip('"')
if what == "pw":
    url = vals.get("DATABASE_URL", "")
    print(u.unquote(u.urlparse(url).password or "") if url else "", end="")
elif what == "jwt":
    print(vals.get("JWT_SECRET", ""), end="")
PY
}

# Bash 3.2 compatible (macOS): per-app values live in PW_<app> / JWT_<app>.
pw_of()  { eval "printf '%s' \"\$PW_$1\""; }
jwt_of() { eval "printf '%s' \"\$JWT_$1\""; }

for app in "${APPS[@]}"; do
  pw=""; jwt=""
  if [[ $ROTATE -eq 0 ]]; then
    pw="$(existing "$app" pw)"
    jwt="$(existing "$app" jwt)"
  fi
  [[ -n "$pw"  ]] || pw="$(openssl rand -hex 24)"
  [[ -n "$jwt" ]] || jwt="$(openssl rand -hex 32)"
  printf -v "PW_$app" '%s' "$pw"
  printf -v "JWT_$app" '%s' "$jwt"
done

# Run the SQL. Output is filtered so no password can reach the terminal even
# inside an error message.
out="$(psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 \
        -v trustit_pw="$PW_trustit" \
        -v amscars_pw="$PW_amscars" \
        -v sift_pw="$PW_sift" \
        -v nexus_pw="$PW_nexus" \
        -f "$SCRIPT_DIR/setup.sql" 2>&1)" && rc=0 || rc=$?
filtered="$out"
for app in "${APPS[@]}"; do
  p="$(pw_of "$app")"
  filtered="${filtered//$p/[redacted]}"
done
printf '%s\n' "$filtered" | grep -viE 'password|postgres(ql)?://' || true
if [[ $rc -ne 0 ]]; then
  echo "error: setup.sql failed (exit $rc)" >&2
  exit "$rc"
fi

# Write the env files. Hosts and database name come from the admin URLs.
for app in "${APPS[@]}"; do
  APP="$app" APP_PW="$(pw_of "$app")" APP_JWT="$(jwt_of "$app")" \
  ADMIN_URL="$ADMIN_URL" ADMIN_URL_POOLED="$ADMIN_URL_POOLED" \
  OUT="$SECRETS_DIR/$app.env" python3 -I - <<'PY'
import os, urllib.parse as u
app = os.environ["APP"]
pw = os.environ["APP_PW"]
jwt = os.environ["APP_JWT"]
direct = u.urlparse(os.environ["ADMIN_URL"])
pooled = u.urlparse(os.environ["ADMIN_URL_POOLED"])
db = direct.path.lstrip("/")
user = f"{app}_app"
cred = f"{u.quote(user, safe='')}:{u.quote(pw, safe='')}"

def host(p):
    return p.hostname + (f":{p.port}" if p.port else "")

lines = [f"# {app}: generated by infra/neon/setup.sh. Do not commit. Do not print."]
if app == "sift":
    lines += [
        f"DATABASE_URL=postgresql://{cred}@{host(direct)}/{db}?sslmode=require",
        f"DATABASE_URL_POOLED=postgresql://{cred}@{host(pooled)}/{db}?sslmode=require",
        f"SPRING_DATASOURCE_URL=jdbc:postgresql://{host(direct)}/{db}?sslmode=require&currentSchema=sift",
        # Pooled JDBC (PgBouncer, transaction mode) must disable server-side prepared statements.
        f"SPRING_DATASOURCE_URL_POOLED=jdbc:postgresql://{host(pooled)}/{db}?sslmode=require&currentSchema=sift&prepareThreshold=0",
        f"SPRING_DATASOURCE_USERNAME={user}",
        f"SPRING_DATASOURCE_PASSWORD={pw}",
        "# Flyway: migrate over the direct URL above (not the pooler); schema is sift.",
        "SPRING_FLYWAY_SCHEMAS=sift",
        "SPRING_FLYWAY_DEFAULT_SCHEMA=sift",
    ]
else:
    lines += [
        f"DATABASE_URL=postgresql://{cred}@{host(direct)}/{db}?schema={app}&sslmode=require",
        f"DATABASE_URL_POOLED=postgresql://{cred}@{host(pooled)}/{db}?schema={app}&sslmode=require&pgbouncer=true",
    ]
lines.append(f"JWT_SECRET={jwt}")

out = os.environ["OUT"]
tmp = out + ".tmp"
fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w", encoding="utf-8") as f:
    for line in lines:
        # Quote values: URLs contain "&", which breaks `. file` in a shell.
        if not line.startswith("#"):
            k, v = line.split("=", 1)
            line = f'{k}="{v}"'
        f.write(line + "\n")
os.chmod(tmp, 0o600)
os.replace(tmp, out)
PY
  echo "wrote $app.env (600)"
done

echo "done: ${APPS[*]}"
